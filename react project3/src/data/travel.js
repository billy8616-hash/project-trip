// 위의 겹겹이 쌓인 courses 를 화면에서 쓰기 편한 "평평한 목록"으로 펼친다.
// 각 코스에 'pohang-food' 같은 고유 id 를 붙이고, spots 도 [배열] → {name,desc,lat,lng} 형태로 바꾼다.
export const COURSES = Object.entries(courses).flatMap(([destinationId, themeMap]) =>
  Object.entries(themeMap).map(([themeId, course]) => ({
    id: `${destinationId}-${themeId}`,
    destinationId,
    themeId,
    title: course.title,
    duration: course.duration,
    distanceKm: course.distanceKm,
    spots: course.spots.map(([name, desc, lat, lng]) => ({ name, desc, lat, lng })),
  })),
)

/* 아래 get... 함수들은 "id 를 주면 해당 정보를 찾아 주는" 도우미다. 못 찾으면 null 을 준다. */

// id 로 여행지 하나 찾기
export function getDestination(id) {
  return DESTINATIONS.find((d) => d.id === id) || null
}

// id 로 테마 하나 찾기
export function getTheme(id) {
  return THEMES.find((t) => t.id === id) || null
}

// 'pohang-food' 같은 코스 id 로 코스 하나 찾기 (상세 화면에서 사용)
export function getCourseById(id) {
  return COURSES.find((c) => c.id === id) || null
}

// 선택 조건(selection)에 맞는 코스들을 걸러서 목록으로 준다.
//   전체 → 모든 코스 / 여행지 → 그 여행지 코스들 / 테마 → 그 테마 코스들
export function getCoursesFor(selection) {
  if (!selection || selection.type === 'all') return COURSES

  if (selection.type === 'destination') {
    return COURSES.filter((c) => c.destinationId === selection.id)
  }

  if (selection.type === 'theme') {
    return COURSES.filter((c) => c.themeId === selection.id)
  }

  return []
}

// [여행지 + 테마] 조합에 딱 맞는 코스 하나 찾기 (미리보기 패널에서 탭을 바꿀 때 사용)
export function getCourseForDestinationTheme(destinationId, themeId) {
  return COURSES.find(
    (course) => course.destinationId === destinationId && course.themeId === themeId,
  ) || null
}
