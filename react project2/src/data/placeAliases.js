//     조선시대에 붙었던 이름이 관광지로 복원된 뒤에도 널리 쓰이는 것이다.)
//
// 아래 목록은 실제 TourAPI 키워드 검색으로 "옛 이름으로는 결과가 0건, 지금 이름으로는
// 나온다"를 하나씩 확인하고 등록한 것이다(그냥 알고 있는 지식만으로 추측해 넣지 않았다).
// 이런 경우를 더 겪을 때마다 같은 방식으로 확인해서 하나씩 추가해 둔다.
//
// 쓰는 곳: lib/course.js (매칭 시 옛 이름도 함께 확인)
// ─────────────────────────────────────────────────────────────

